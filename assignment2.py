# Create variables for the 4 basic Python data types
text_var = "Hello, Python!"  # str (string)
integer_var = 42             # int (integer)
float_var = 3.14             # float (floating-point number)
boolean_var = True           # bool (boolean)

# Print each variable and its corresponding data type
print("Value:", text_var, "| Type:", type(text_var))
print("Value:", integer_var, "| Type:", type(integer_var))
print("Value:", float_var, "| Type:", type(float_var))
print("Value:", boolean_var, "| Type:", type(boolean_var))